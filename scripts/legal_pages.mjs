      <p>運営者は、本サービスの判定の結果によって利用者に生じた損害について、運営者に故意または重大な過失がある場合を除き、責任を負いません。運営者が責任を負う場合でも、その額は利用者が直近1か月に支払った料金を上限とします。ただし、消費者契約法その他の法令により免責が認められない場合は、この限りではありません。</p>

