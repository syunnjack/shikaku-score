import { LEGAL, PLAN, yen } from '../lib/legal.mjs'

const ON_REQUEST = '請求があった場合は、遅滞なく開示します。'

function shell({ css, escapeHtml, title, body }) {
  return `<!doctype html>
<html lang="ja">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${escapeHtml(title)}｜合格ラインとの距離</title>
    <meta name="robots" content="noindex" />
    <style>${css}
.legal h2 { font-size:16px; margin:26px 0 8px; }
.legal p, .legal li { font-size:14px; }
.legal ol, .legal ul { padding-left:22px; }
.legal table { width:100%; border-collapse:collapse; font-size:14px; background:#fff; }
.legal th, .legal td { border:1px solid #e2e6ef; padding:10px 12px; text-align:left; vertical-align:top; }
.legal th { width:34%; background:#f2f5fa; font-weight:600; }</style>
  </head>
  <body>
    <div class="wrap legal">
      <p class="full"><a href="/">← 合格ラインとの距離</a></p>
      <h1>${escapeHtml(title)}</h1>
${body}
    </div>
  </body>
</html>
`
}

