  const e = escapeHtml
  const price = e(yen(LEGAL.priceMonthlyYen))
  const address = LEGAL.discloseOnRequest && !LEGAL.address ? ON_REQUEST : e(LEGAL.address)
  const phone = LEGAL.discloseOnRequest && !LEGAL.phone ? ON_REQUEST : e(LEGAL.phone)
  const mail = `<a href="mailto:${e(LEGAL.email)}">${e(LEGAL.email)}</a>`
  const since = e(LEGAL.effectiveDate)
  const feats = PLAN.features.map((f) => '<li>' + e(f) + '</li>').join('')

  const rows = [
    ['販売事業者', e(LEGAL.seller)],
    ['運営統括責任者', e(LEGAL.manager)],
    ['所在地', address],
    ['電話番号', phone],
    ['メールアドレス', mail + '<br />お問い合わせはメールでお願いします。'],
    ['販売価格', e(PLAN.name) + '　月額' + price + '（税込）'],
    ['商品代金以外の必要料金', 'インターネット接続にかかる通信料はお客様のご負担です。'],
    ['支払方法', 'クレジットカード（決済は Stripe を通じて行います）'],
    ['支払時期', '申込時に初月分を請求し、以後は申込日を起点に1か月ごとに自動で請求します。'],
    ['提供時期', '決済の完了後、すぐにご利用いただけます。'],
    ['契約期間・自動更新', '1か月ごとの自動更新です。解約の手続きをするまで継続します。'],
    ['解約', '会員欄の「解約する・支払い方法を変える」から、いつでも解約できます。' +
      '解約後も、支払い済みの期間の終わりまでご利用いただけます。'],
    ['返金', 'デジタルサービスの性質上、支払い後の返金および日割りの返金はいたしません。' +
      'ただし、当方の責めによりサービスを提供できなかった場合はこの限りではありません。'],
    ['動作環境', 'JavaScript が有効な最新のブラウザ（Chrome、Safari、Edge、Firefox）'],
  ]

  const tokushoho = shell({ css, escapeHtml, title: '特定商取引法に基づく表記', body:
    '<table>' + rows.map(([k, v]) => `<tr><th>${k}</th><td>${v}</td></tr>`).join('') + '</table>' })

